# Data: metadata, anti-leak split, smoke subsample (identical to notebooks)
# --------------------------------------------------------------------------
class SplitData:
    def __init__(self, classes, paths, id2label, tr_ids, va_ids, split_desc):
        self.classes = classes
        self.paths = paths
        self.id2label = id2label
        self.tr_ids = tr_ids
        self.va_ids = va_ids
        self.split_desc = split_desc
        self.y_tr = np.array([id2label[i] for i in tr_ids])
        self.y_va = np.array([id2label[i] for i in va_ids])

    @property
    def n_classes(self) -> int:
        return len(self.classes)


def _load_ham(dataset_dir: Path):
    meta = pd.read_csv(find_files([dataset_dir], "HAM10000_metadata.csv")[0])
    paths = index_images([dataset_dir])
    meta = meta[meta.image_id.isin(paths)].reset_index(drop=True)
    classes = sorted(meta.dx.unique())
    cls2idx = {c: i for i, c in enumerate(classes)}
    id2label = {r.image_id: cls2idx[r.dx] for r in meta.itertuples()}
    ids = meta.image_id.astype(str).tolist()
    groups = meta.lesion_id.astype(str).values
    desc = "StratifiedGroupKFold por lesion_id (0 lesiones compartidas)"
    return classes, paths, id2label, ids, groups, desc


def _load_isic(dataset_dir: Path, spec: protocol.DatasetSpec):
    meta = pd.read_csv(find_files([dataset_dir], spec.metadata_csv)[0])
    id_col = next(c for c in ("isic_id", "image_name", "image_id", "image")
                  if c in meta.columns)
    assert "target" in meta.columns, f"sin columna target: {list(meta.columns)}"
    paths = index_images([dataset_dir])
    meta = meta[meta[id_col].astype(str).isin(paths)].reset_index(drop=True)
    classes = ["benign", "malignant"]
    id2label = {str(r): int(t) for r, t in zip(meta[id_col], meta.target)}
    ids = meta[id_col].astype(str).tolist()
    if spec.group_column and spec.group_column in meta.columns:
        groups = meta[spec.group_column].astype(str).values
        desc = f"StratifiedGroupKFold por {spec.group_column} (0 grupos compartidos)"
    else:
        groups = np.array(ids)
        desc = "estratificado simple (sin grupo real disponible en RESIZED)"
    return classes, paths, id2label, ids, groups, desc


def _load_isic2019(dataset_dir: Path, spec: protocol.DatasetSpec):
    """ISIC 2019 official ground truth: one-hot columns, no grouping column.

    Mirrors ``DATA_CODE_ISIC2019MC`` in ``scripts/build_finetune_tests.py`` so
    the cluster and the Kaggle notebooks read the labels identically.

    Two limits travel with this dataset and are surfaced in ``split_desc`` so
    they reach the results JSON instead of living only in a comment:
    the release ships no real patient/lesion column (the RESIZED variant's
    patient_id is synthetic), so the split is stratified only; and its training
    set contains HAM10000, so the two datasets of the bank overlap.
    """
    meta = pd.read_csv(find_files([dataset_dir], spec.metadata_csv)[0])
    id_col = meta.columns[0]                      # "image"
    dropped = [c for c in protocol.ISIC2019_DROPPED_COLUMNS if c in meta.columns]
    onehot = meta.drop(columns=[id_col, *dropped])
    classes = list(onehot.columns)
    assert tuple(classes) == protocol.ISIC2019_CLASSES, (
        f"columnas {tuple(classes)} != protocolo {protocol.ISIC2019_CLASSES}; "
        "el ground truth cambio y la corrida NO es comparable con el banco.")
    cls2idx = {c: i for i, c in enumerate(classes)}
    labels = onehot.idxmax(axis=1)                # one-hot -> class name
    paths = index_images([dataset_dir])
    meta = meta.assign(_label=labels)
    meta = meta[meta[id_col].astype(str).isin(paths)].reset_index(drop=True)
    id2label = {str(r): cls2idx[lab]
                for r, lab in zip(meta[id_col], meta._label)}
    ids = meta[id_col].astype(str).tolist()
    # One group per image degenerates StratifiedGroupKFold into a plain
    # stratified split, which is exactly what this release allows.
    groups = np.array(ids)
    desc = ("estratificado simple SIN grupo de paciente (el release no lo trae) "
            "- riesgo de fuga entre imagenes del mismo paciente y solape con "
            "HAM10000, metricas con sesgo optimista")
    return classes, paths, id2label, ids, groups, desc


def load_split(cfg: FinetuneConfig) -> SplitData:
    spec = cfg.dataset_spec
    if spec.name == "isic2019":
        classes, paths, id2label, ids, groups, desc = _load_isic2019(
            cfg.dataset_dir, spec)
    elif spec.task == "multiclass":
        classes, paths, id2label, ids, groups, desc = _load_ham(cfg.dataset_dir)
    else:
        classes, paths, id2label, ids, groups, desc = _load_isic(cfg.dataset_dir, spec)
    n = len(classes)
    y = np.array([id2label[i] for i in ids])
    tr_idx, va_idx = next(StratifiedGroupKFold(5, shuffle=True, random_state=cfg.seed)
                          .split(ids, y, groups))
    tr_ids = [ids[i] for i in tr_idx]
    va_ids = [ids[i] for i in va_idx]
    g = dict(zip(ids, groups))
    shared = {g[i] for i in tr_ids} & {g[i] for i in va_ids}
    assert not shared, f"LEAKAGE: {len(shared)} grupos compartidos"

    if cfg.smoke:
        frac, min_tr, min_va = protocol.SMOKE_FRACTION[cfg.dataset]
        rng = np.random.default_rng(cfg.seed)

        def subsample(id_list, min_pc):
            yy = np.array([id2label[i] for i in id_list])
            keep = []
            for c in range(n):
                idx = np.flatnonzero(yy == c)
                take = max(min_pc, int(len(idx) * frac))
                keep.extend(rng.choice(idx, size=min(take, len(idx)), replace=False))
            return [id_list[i] for i in sorted(keep)]

        tr_ids, va_ids = subsample(tr_ids, min_tr), subsample(va_ids, min_va)
    return SplitData(classes, paths, id2label, tr_ids, va_ids, desc)


# --------------------------------------------------------------------------
# Backbones: Hugging Face Hub via timm (+ the two documented exceptions)
# --------------------------------------------------------------------------
def _gap(features: nn.Module) -> nn.Module:
    return nn.Sequential(features, nn.AdaptiveAvgPool2d(1), nn.Flatten(1))


def load_backbone(name: str):
    """Return (backbone, interpolation). Weights per protocol.TIMM_HF_TAGS."""
    res, interp = protocol.RESOLUTION, transforms.InterpolationMode.BILINEAR
    if name == "alexnet":
        from torchvision.models import AlexNet_Weights, alexnet
        return _gap(alexnet(weights=AlexNet_Weights.IMAGENET1K_V1).features), interp
    if name == "simsiam_r50":
        from torchvision.models import resnet50
        sd = torch.hub.load_state_dict_from_url(
            protocol.SIMSIAM_CHECKPOINT_URL, map_location="cpu")["state_dict"]
        sd = {k.replace("module.encoder.", ""): v for k, v in sd.items()
              if k.startswith("module.encoder.") and not k.startswith("module.encoder.fc")}
        m = resnet50()
        m.fc = nn.Identity()
        missing, unexpected = m.load_state_dict(sd, strict=False)
        assert not unexpected, f"claves inesperadas: {unexpected[:5]}"
        return m, interp
    import timm
    tag = protocol.TIMM_HF_TAGS[name]
    if name == "efficientnet_b0":
        interp = transforms.InterpolationMode.BICUBIC
    kwargs = {"img_size": res} if "patch14" in tag else {}
    m = timm.create_model(tag, pretrained=True, num_classes=0, **kwargs)
    if name in protocol.CONV_GAP_FROM_TIMM:
        # num_classes=0 leaves VGG's 4096-d pre-logits in place; the bank reads
        # every CNN at the GAP of its last conv block. The list lives in
        # protocol so adding a backbone here does not mean editing this branch.
        return _gap(m.features), interp
    return m, interp


class FTNet(nn.Module):
    def __init__(self, backbone: nn.Module, dim: int, n_cls: int):
        super().__init__()
        self.backbone = backbone
        self.head = nn.Linear(dim, n_cls)

    def forward(self, x):
        return self.head(self.backbone(x))


class FTDataset(Dataset):
    def __init__(self, ids, paths, id2label, tf):
        self.ids, self.paths, self.id2label, self.tf = ids, paths, id2label, tf

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, i):
        img = Image.open(self.paths[self.ids[i]]).convert("RGB")
        return self.tf(img), self.id2label[self.ids[i]]


def build_transforms(interp):
    res, mean, std = protocol.RESOLUTION, protocol.IMAGENET_MEAN, protocol.IMAGENET_STD
    train = transforms.Compose([
        transforms.Resize(int(res * 1.14), interpolation=interp),
        transforms.RandomCrop(res),
        transforms.RandomHorizontalFlip(),
        transforms.RandomVerticalFlip(),
        transforms.ColorJitter(0.1, 0.1, 0.05),
        transforms.ToTensor(),
        transforms.Normalize(mean, std),
    ])
    evaluate = transforms.Compose([
        transforms.Resize(int(res * 1.14), interpolation=interp),
        transforms.CenterCrop(res),
        transforms.ToTensor(),
        transforms.Normalize(mean, std),
    ])
    return train, evaluate


