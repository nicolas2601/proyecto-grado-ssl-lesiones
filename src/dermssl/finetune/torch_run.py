def git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], text=True,
            cwd=Path(__file__).resolve().parents[3], stderr=subprocess.DEVNULL).strip()
    except Exception:  # noqa: BLE001 - provenance is best effort
        return "unknown"


def _autocast_dtype(precision: str):
    return {"fp16": torch.float16, "bf16": torch.bfloat16}.get(precision)


# --------------------------------------------------------------------------
# One job end to end
# --------------------------------------------------------------------------
def run(cfg: FinetuneConfig, tracker: CompositeTracker) -> Path:
    torch.manual_seed(cfg.seed)
    np.random.seed(cfg.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    out_dir = Path(cfg.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    job = next(j for j in protocol.manifest()
               if j.model == cfg.model and j.dataset == cfg.dataset)
    print(f"[{job.run_name}] device={device} smoke={cfg.smoke} "
          f"pesos={weight_source(cfg.model)}")

    data = load_split(cfg)
    n = data.n_classes
    print(f"clases={data.classes} train={len(data.tr_ids)} val={len(data.va_ids)} "
          f"| {data.split_desc}")

    backbone, interp = load_backbone(cfg.model)
    backbone.eval().to(device)
    with torch.no_grad():
        dim = backbone(torch.zeros(1, 3, protocol.RESOLUTION, protocol.RESOLUTION,
                                   device=device)).shape[-1]
    expected = protocol.FEATURE_DIMS[cfg.model]
    assert dim == expected, (
        f"{cfg.model}: se extrajeron {dim} dims, el protocolo fija {expected}. "
        "El punto de extraccion cambio; la corrida NO es comparable con el banco.")
    for p in backbone.parameters():
        p.requires_grad = True
    net = FTNet(backbone, dim, n).to(device)

    tf_train, tf_eval = build_transforms(interp)
    batch = cfg.effective_batch
    dl_tr = DataLoader(FTDataset(data.tr_ids, data.paths, data.id2label, tf_train),
                       batch_size=batch, shuffle=True, num_workers=cfg.num_workers,
                       pin_memory=True, drop_last=True)
    dl_va = DataLoader(FTDataset(data.va_ids, data.paths, data.id2label, tf_eval),
                       batch_size=batch, shuffle=False, num_workers=cfg.num_workers,
                       pin_memory=True)

    counts = np.bincount(data.y_tr, minlength=n).astype(float)
    class_w = torch.tensor(counts.sum() / (n * counts), dtype=torch.float32, device=device)
    criterion = nn.CrossEntropyLoss(weight=class_w)
    optimizer = torch.optim.AdamW([
        {"params": net.backbone.parameters(), "lr": cfg.lr_backbone},
        {"params": net.head.parameters(), "lr": cfg.lr_head},
    ], weight_decay=cfg.weight_decay)
    epochs = cfg.effective_epochs
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=max(1, epochs * len(dl_tr)))
    amp_dtype = _autocast_dtype(cfg.precision) if device.type == "cuda" else None
    scaler = torch.amp.GradScaler("cuda", enabled=amp_dtype is torch.float16)

    params = {**cfg.as_params(), "dim_features": int(dim), "n_train": len(data.tr_ids),
              "n_val": len(data.va_ids), "split": data.split_desc, "git_sha": git_sha(),
              "host": platform.node(),
              "gpu": torch.cuda.get_device_name(0) if device.type == "cuda" else "cpu"}
    tracker.start(params)

    best_ba, best_sd, best_epoch = -1.0, None, -1
    t0 = time.time()
    for epoch in range(epochs):
        net.train()
        running, seen = 0.0, 0
        for xb, yb in dl_tr:
            xb = xb.to(device, non_blocking=True)
            yb = yb.to(device, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            with torch.autocast(device_type=device.type, dtype=amp_dtype,
                                enabled=amp_dtype is not None):
                loss = criterion(net(xb), yb)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
            scheduler.step()
            running += loss.item() * len(yb)
            seen += len(yb)
        net.eval()
        preds = []
        with torch.no_grad():
            for xb, _ in dl_va:
                with torch.autocast(device_type=device.type, dtype=amp_dtype,
                                    enabled=amp_dtype is not None):
                    out = net(xb.to(device, non_blocking=True))
                preds.append(out.float().argmax(1).cpu().numpy())
        ba = balanced_accuracy_score(data.y_va, np.concatenate(preds))
        if ba > best_ba:
            best_ba, best_sd, best_epoch = ba, copy.deepcopy(net.state_dict()), epoch + 1
        train_loss = running / max(1, seen)
        tracker.log_metrics({"train/loss": train_loss, "val/balanced_accuracy": ba,
                             "val/best_balanced_accuracy": best_ba,
                             "lr/backbone": optimizer.param_groups[0]["lr"],
                             "tiempo_s": time.time() - t0}, step=epoch + 1)
        print(f"epoca {epoch + 1}/{epochs} loss={train_loss:.4f} val_bal_acc={ba:.4f} "
              f"mejor={best_ba:.4f} ({time.time() - t0:.0f}s)")

    net.load_state_dict(best_sd)
    net.eval()
    probs = []
    with torch.no_grad():
        for xb, _ in dl_va:
            out = net(xb.to(device, non_blocking=True))
            probs.append(torch.softmax(out.float(), 1).cpu().numpy())
    proba_va = np.concatenate(probs)
    metrics = all_metrics(data.y_va, proba_va, data.classes, cfg.seed)

    results = {
        "modelo": cfg.model, "dataset": cfg.dataset, "smoke": cfg.smoke,
        "n_train": len(data.tr_ids), "n_val": len(data.va_ids),
        "dim_features": int(dim), "resolucion": protocol.RESOLUTION,
        "semilla": cfg.seed, "split": data.split_desc,
        "protocolo": {k: params[k] for k in ("epocas", "batch", "lr_backbone",
                                               "lr_head", "weight_decay", "precision")},
        "fuente_pesos": params["fuente_pesos"], "git_sha": params["git_sha"],
        "host": params["host"], "gpu": params["gpu"],
        "mejor_epoca": best_epoch, "tiempo_s": round(time.time() - t0, 1),
        "probes": {"finetune": metrics},
    }
    json_path = out_dir / job.results_file
    json_path.write_text(json.dumps(results, indent=2))
    ckpt = out_dir / job.checkpoint_file
    torch.save({"modelo": cfg.model, "dataset": cfg.dataset, "smoke": cfg.smoke,
                "clases": data.classes, "state_dict": net.state_dict()}, ckpt)

    tracker.log_metrics({f"final/{k}": v for k, v in metrics.items()})
    tracker.log_artifact(str(json_path))
    tracker.end()

    m = metrics
    print(("ATENCION: numeros de SMOKE, no validos\n" if cfg.smoke else "") + "-" * 70)
    print(f"{cfg.model} @ {cfg.dataset} | val n={len(data.va_ids)} | mejor epoca {best_epoch}")
    print(f"bal_acc={m['balanced_accuracy']:.4f} macro_f1={m['macro_f1']:.4f} "
          f"auc={m['auc_ovr_macro']:.4f} acc={m['accuracy']:.4f} ece={m['ece']:.4f}")
    ci = m["ic95_bootstrap"]
    print("IC95 bootstrap: bal_acc {:.3f}-{:.3f} | F1 macro {:.3f}-{:.3f}".format(
        *ci["balanced_accuracy"], *ci["macro_f1"]))
    print("-" * 70)
    print("resultados:", json_path)
    print("checkpoint:", ckpt)
    return json_path
