def bootstrap_ci(y_true, pred, seed, n_resamples=1000):
    rng = np.random.default_rng(seed)
    idx_all = np.arange(len(y_true))
    ba, f1v = [], []
    for _ in range(n_resamples):
        idx = rng.choice(idx_all, size=len(idx_all), replace=True)
        ba.append(balanced_accuracy_score(y_true[idx], pred[idx]))
        f1v.append(f1_score(y_true[idx], pred[idx], average="macro"))

    def pct(v):
        return [float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))]

    return {"balanced_accuracy": pct(ba), "macro_f1": pct(f1v)}


def ece(y_true, proba, bins=15):
    conf, pred = proba.max(1), proba.argmax(1)
    ok = (pred == y_true).astype(float)
    edges = np.linspace(0, 1, bins + 1)
    tot = 0.0
    for i in range(bins):
        m = ((conf > edges[i]) & (conf <= edges[i + 1]) if i
             else (conf >= 0) & (conf <= edges[1]))
        if m.any():
            tot += m.mean() * abs(conf[m].mean() - ok[m].mean())
    return float(tot)


def all_metrics(y_true, proba, classes, seed):
    n = len(classes)
    pred = proba.argmax(1)

    def per_class(fn):
        return {classes[c]: float(fn(y_true, pred, labels=[c], average="macro",
                                     zero_division=0)) for c in range(n)}

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return {
            "accuracy": accuracy_score(y_true, pred),
            "balanced_accuracy": balanced_accuracy_score(y_true, pred),
            "macro_f1": f1_score(y_true, pred, average="macro"),
            "macro_precision": precision_score(y_true, pred, average="macro", zero_division=0),
            "macro_recall": recall_score(y_true, pred, average="macro", zero_division=0),
            "auc_ovr_macro": (roc_auc_score(y_true, proba[:, 1]) if n == 2 else
                              roc_auc_score(y_true, proba, multi_class="ovr",
                                            average="macro", labels=list(range(n)))),
            "ece": ece(y_true, proba),
            "recall_por_clase": per_class(recall_score),
            "precision_por_clase": per_class(precision_score),
            "f1_por_clase": per_class(f1_score),
            "matriz_confusion": confusion_matrix(y_true, pred, labels=list(range(n))).tolist(),
            "ic95_bootstrap": bootstrap_ci(y_true, pred, seed),
        }


