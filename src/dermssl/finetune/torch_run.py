"""The torch half of one fine-tuning job (cluster runner).

Mirrors, cell by cell, the Kaggle notebooks generated by
``scripts/build_finetune_tests.py``: same data loading, same anti-leak
split, same backbone loaders (Hugging Face Hub via timm), same training
recipe, same metric suite and the same results JSON schema. The only
differences are the data root (a folder instead of /kaggle/input) and the
trackers (W&B + MLflow instead of MLflow alone).

Import this module only after :func:`dermssl.finetune.config.validate` has
accepted the configuration: it imports torch at module load.
"""

