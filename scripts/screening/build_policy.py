#!/usr/bin/env python3
"""Build the shipped screening policy and its summary from screening-report.json (no new numbers)."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

SCHEMA = "dermssl.screening-policy.v1"
RULE_ID = "melanoma-priority-v1"
SHIPPED_SEED = "42"
PUBLIC_METRICS = ("target_recall", "target_to_nevus", "nevus_recall", "target_precision",
                  "target_alert_rate", "macro_f1")
SCOPE = ("Development out-of-fold operating point (grouped CV, shipped encoder). "
         "No sealed-test evaluation exists for it. Scores are not clinical probabilities.")


def _public(metrics: dict) -> dict:
    return {key: round(float(metrics[key]), 4) for key in PUBLIC_METRICS}


def build_policy(report: dict, report_sha256: str) -> dict:
    heads = {}
    for task, spec in report["tasks"].items():
        shipped = spec["by_encoder_seed"][SHIPPED_SEED]
        heads[spec["model_key"]] = {
            "task": task, "target": spec["target"], "log_offset": float(spec["delta"]),
            "head_sha256": spec["head_sha256"],
            "development": {"at_zero": _public(shipped["at_zero"]), "nested": _public(shipped["nested"])},
        }
    return {"schema": SCHEMA, "rule_id": RULE_ID, "release": report["release"],
            "model_sha256": report["model_sha256"], "manifest_sha256": report["manifest_sha256"],
            "scope": SCOPE, "heads": heads,
            "evidence": {"report_sha256": report_sha256, "rule_sha256": report["rule_sha256"]}}


def _row(name: str, at_zero: dict, nested: dict, key: str) -> str:
    return f"| {name} | {at_zero[key]:.3f} | {nested[key]:.3f} |"


def summary_markdown(report: dict) -> str:
    lines = ["# Melanoma-priority operating point: development results", "",
             "Generated by `scripts/screening/build_policy.py` from `screening-report.json`. "
             "Rule: `RULE.md`. Development data only; no sealed-test number exists for this operating point.", ""]
    for task, spec in report["tasks"].items():
        lines += [f"## {task} (target `{spec['target']}`, log offset {spec['delta']})", "",
                  "Nested held-out estimates, mean of 3 CV seeds per encoder seed.", "",
                  "| Encoder seed | Selected offset | Recall (shipped argmax) | Recall (screening) | "
                  "Target to nevus | Nevus recall | Macro-F1 | Alert rate |",
                  "|---|---|---|---|---|---|---|---|"]
        for seed, block in spec["by_encoder_seed"].items():
            z, n = block["at_zero"], block["nested"]
            lines.append(
                f"| {seed} | {block['selected_delta']} | {z['target_recall']:.3f} | {n['target_recall']:.3f} | "
                f"{z['target_to_nevus']:.3f} -> {n['target_to_nevus']:.3f} | "
                f"{z['nevus_recall']:.3f} -> {n['nevus_recall']:.3f} | "
                f"{z['macro_f1']:.3f} -> {n['macro_f1']:.3f} | "
                f"{z['target_alert_rate']:.3f} -> {n['target_alert_rate']:.3f} |")
        check = spec["shipped_head_check"]
        lines += ["", f"Refit of the shipped recipe vs the bundle head (encoder 42): max probability "
                  f"difference {check['max_abs_probability_diff']:.4f}, argmax agreement "
                  f"{check['argmax_agreement']:.4f}.", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    content = args.report.read_bytes()
    report = json.loads(content)
    policy = build_policy(report, hashlib.sha256(content).hexdigest())
    args.output.mkdir(parents=True, exist_ok=True)
    policy_bytes = (json.dumps(policy, indent=2, allow_nan=False) + "\n").encode()
    (args.output / "screening_policy.json").write_bytes(policy_bytes)
    (args.output / "SCREENING.md").write_text(summary_markdown(report) + "\n")
    print(json.dumps({"policy_sha256": hashlib.sha256(policy_bytes).hexdigest(),
                      "offsets": {k: v["log_offset"] for k, v in policy["heads"].items()}}))


if __name__ == "__main__":
    main()
