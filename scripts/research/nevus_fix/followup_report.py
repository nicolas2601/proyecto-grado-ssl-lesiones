#!/usr/bin/env python3
"""Render the v10.4 follow-up arms (JSON in resultados/clasificacion/v10.4/followup) into FOLLOWUP.md tables."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

EXTERNAL = ("milk_test", "pad_test", "ham_holdout", "ddi", "fitz", "bosque", "internet")


def load(root, name):
    return json.loads((root / f"{name}.json").read_text())


def f(v):
    return "–" if v is None else f"{v:.3f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def readers(root):
    lab = load(root, "lab-base")
    rows = [[t, f(lab["selection"]["scores"][t])] + [f(v["sets"][s]["balanced_accuracy"]) for s in EXTERNAL]
            for t, v in lab["variants"].items()]
    return table(["reader", "milk_dev score*"] + list(EXTERNAL), rows)


def study_row(study, label):
    best = study["selection"]["best"]
    r = study["readers"][best]
    return [label, f(study["selection"]["scores"][best])] + [f(r[s]["all"]["balanced_accuracy"]) for s in EXTERNAL]


def views(root):
    rows = []
    for name in ("crop-c70", "crop-c50"):
        for tag, v in load(root, name).items():
            if tag == "squash" and name == "crop-c50":
                continue
            rows.append([f"{tag} (shipped head)", f(v["dev_score"])] +
                        [f(v[s]["all"]["balanced_accuracy"]) if s in v else "–" for s in EXTERNAL])
    rows.append(study_row(load(root, "study-c70"), "c70 refit reader"))
    rows.append(study_row(load(root, "study-isicclin"), "squash + ISIC clinical rows"))
    for name, label in (("views-samehead", "shipped head"), ("views-sq-c70", "c70 refit head")):
        for tag in ("mean", "minent"):
            v = load(root, name)["summary"][tag]
            rows.append([f"squash+c70 {tag} ({label})", f(v["dev_score"])] + [f(v["bacc"].get(s)) for s in EXTERNAL])
    return table(["view / reader", "milk_dev score"] + list(EXTERNAL), rows)


def bootstrap(root):
    rows = []
    for name, label in (("boot-samehead", "shipped head"), ("boot-c70head", "c70 refit head")):
        for s, v in load(root, name).items():
            rows.append([label, s, v["n"], f(v["bacc_base"]), f(v["bacc_views"]),
                         f"{v['diff']:+.3f} [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}]"])
    return table(["second view head", "set", "n", "bacc shipped", "bacc 2-view", "diff [95% CI]"], rows)


def target_cv(root):
    rows = []
    for name in ("targetcv-ddi", "targetcv-bosque", "targetcv-ddi+bosque"):
        for t, r in load(root, name)["cv"].items():
            rows.append([name.removeprefix("targetcv-"), t, f(r["balanced_accuracy"]), f(r["malignant_auc"]),
                         f(r["recall"].get("mel")), f(r["recall"].get("nv"))])
    return table(["rows added", "scored on (5-fold, grouped)", "bacc", "malignant AUC", "mel recall", "nv recall"], rows)


def nv_curve(root):
    out = []
    for s, rows in load(root, "nv-priority-curve").items():
        out += [f"**{s}**", ""] + table(
            ["nevus offset", "nevi correct", "melanoma → nevus", "non-nevus → nevus", "bacc"],
            [[r["offset"], f"{r['nevus_ok']}/{r['nevi']}", f"{r['mel_to_nv']}/{r['mel']}",
              f"{r['non_nv_to_nv']}/{r['non_nv']}", f(r["bacc"])] for r in rows]) + [""]
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    r = args.root
    lines = ["# v10.4 follow-up arms (generated by `scripts/research/nevus_fix/followup_report.py`)", "",
             "All arms keep the SSL encoder frozen; labels only enter the reader. Selection score = milk_dev "
             "clinical bacc + 0.5 × dermoscopic bacc. Other sets are report-only.", "",
             "## Reader variants on the shipped view", "", *readers(r), "",
             "*Nested (5-fold grouped) estimate for the offset variants; MLP epochs are picked on milk_dev.", "",
             "## Views and extra clinical rows", "", *views(r), "",
             "## Two-view min-entropy against the shipped view (paired bootstrap, 2,000 draws)", "", *bootstrap(r), "",
             "## Target-domain rows (cross-validated; these sets stop being external tests)", "", *target_cv(r), "",
             "## Cost of a larger nevus prior (shipped head)", "", *nv_curve(r)]
    args.out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
