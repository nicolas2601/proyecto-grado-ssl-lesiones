#!/usr/bin/env python3
"""Render the v10.5.0 evidence (resultados/clasificacion/v10.5/evidence) into RESULTS.md tables."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

SETS = ("milk_dev", "milk_test", "pad_test", "ham_holdout", "ddi", "fitz", "bosque", "internet")


def f(v, d=3):
    return "–" if v is None else f"{v:.{d}f}"


def table(header, rows):
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + [
        "| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def boot(path: Path, base: str, cand: str):
    report = json.loads(path.read_text())["sets"]
    rows = [[s, r["n"], f(r["bacc"][0]), f(r["bacc"][1]), f"{r['diff']:+.3f} [{r['ci95'][0]:+.3f}, {r['ci95'][1]:+.3f}]",
             f"{f(r['mel_recall'][0], 2)} → {f(r['mel_recall'][1], 2)}", f"{f(r['malignant_auc'][0])} → {f(r['malignant_auc'][1])}"]
            for s, r in report.items()]
    return table(["set", "n", f"bacc {base}", f"bacc {cand}", "diff [95% CI]", "mel recall", "malignant AUC"], rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    e = args.root / "evidence"
    refit = json.loads((e / "views-refit.json").read_text())
    verify = json.loads((e / "candidate-validation.json").read_text())
    screening = json.loads((args.root / "screening/screening-report.json").read_text())
    t = verify["timings"]
    lines = ["# v10.5.0 evidence (generated by `scripts/research/nevus_fix/v10_5_report.py`)", "",
             "## Served recipe: 8 D4 views vs 1 view, FP32 features as served (paired bootstrap, 2,000 draws)", "",
             *boot(e / "boot-fp32-final.json", "8 views", "1 view"), "",
             "## View subsets, HAM7 reader refit per recipe (bf16 study features)", "",
             *table(["recipe", "ViT passes", "milk_dev score"] + list(SETS),
                    [[tag, r["views"], f(r["dev_score"])] + [f(r["sets"][s]["all"]["balanced_accuracy"]) for s in SETS]
                     for tag, r in refit.items()]), "",
             "## Single view plus a 70% centre crop (min-entropy) vs single view (bf16)", "",
             *boot(e / "boot-1view-2crop.json", "1 view", "1 view + crop"), "",
             "## Melanoma-priority offset (rule: screening/RULE.md)", "",
             f"Selected offset {screening['selected_delta']}; nested fold offsets {screening['nested']['fold_deltas']}; "
             f"milk_dev melanoma recall {f(screening['nested']['at_zero']['target_recall'])} at 0 → "
             f"{f(screening['nested']['metrics']['target_recall'])} nested; macro-F1 "
             f"{f(screening['nested']['at_zero']['macro_f1'])} → {f(screening['nested']['metrics']['macro_f1'])}.", "",
             "## Candidate verification on the production host", "",
             f"{sum(c['passed'] for c in verify['checks'])}/{len(verify['checks'])} checks passed; /api/analyze wall "
             f"p50 {t['analyze_p50_wall_s']} s (sequential {t['analyze_sequential_wall_s']}); server classification "
             f"{t['analyze_server_classification_ms']} ms; two concurrent requests {t['concurrent_2']['total_s']} s.", "",
             "v10.4.0 reference: `evidence/latency-v10.4-predict.txt`. INT8 dynamic quantisation was rejected: "
             "`evidence/int8-parity.log` (agreement with the reference) vs `evidence/fp32-parity.log` (FP32 control)."]
    args.out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
